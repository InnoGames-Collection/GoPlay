// Flattened master pool for background floaters & random picks
export const ALL_EMOJIS = Object.values(EMOJI_POOL).flat();

/**
 * Returns n unique random emojis from the master pool
 */
export function getRandomEmojis(count: number, exclude: string[] = []): string[] {
  const available = ALL_EMOJIS.filter((e) => !exclude.includes(e));
  const shuffled = [...available].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}
